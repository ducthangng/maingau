// Generate src/types/contracts.ts from docs/schema/*.json (exported from nba/contracts.py by Agent KG).
// Never edit the output by hand; rerun `npm run types` after a contract change.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = resolve(here, "../../docs/schema");
const outFile = resolve(here, "../src/types/contracts.ts");

const MODELS = {
  customer_card: "CustomerCard",
  index_row: "IndexRow",
  summary: "Summary",
  decision_request: "DecisionRequest",
  journey: "Journey",
};

// Pydantic puts a title on every property; json-schema-to-typescript would turn each one
// into its own type alias. Keep titles only on named definitions.
const TYPED_KEYS = ["type", "$ref", "anyOf", "oneOf", "allOf", "enum", "const", "properties", "items", "additionalProperties"];

// A pydantic `Any` field has no type at all; without this it would become an object type.
const typed = (schema) =>
  schema && typeof schema === "object" && !TYPED_KEYS.some((k) => k in schema) ? { ...schema, tsType: "unknown" } : schema;

function stripTitles(node) {
  if (Array.isArray(node)) return node.map(stripTitles);
  if (node && typeof node === "object") {
    const out = {};
    for (const [k, v] of Object.entries(node)) {
      if (k === "title") continue;
      if (k === "properties") {
        out[k] = Object.fromEntries(Object.entries(v).map(([name, s]) => [name, typed(stripTitles(s))]));
      } else if (k === "items" || k === "additionalProperties") {
        out[k] = typeof v === "object" ? typed(stripTitles(v)) : v;
      } else {
        out[k] = stripTitles(v);
      }
    }
    return out;
  }
  return node;
}

const defs = {};
const properties = {};
for (const [file, name] of Object.entries(MODELS)) {
  const schema = JSON.parse(readFileSync(resolve(schemaDir, `${file}.schema.json`), "utf8"));
  const { $defs = {}, ...root } = schema;
  for (const [defName, def] of Object.entries({ ...$defs, [name]: root })) {
    const clean = { ...stripTitles(def), title: defName };
    if (defs[defName] && JSON.stringify(defs[defName]) !== JSON.stringify(clean)) {
      throw new Error(`definition ${defName} differs between schema files`);
    }
    defs[defName] = clean;
  }
  properties[file] = { $ref: `#/$defs/${name}` };
}

const combined = {
  title: "Contracts",
  type: "object",
  properties,
  required: Object.keys(properties),
  additionalProperties: false,
  $defs: defs,
};

const banner = [
  "/* eslint-disable */",
  "// Generated by web/scripts/gen-types.mjs from docs/schema/*.json (nba/contracts.py). Do not edit.",
].join("\n");
const ts = await compile(combined, "Contracts", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { semi: true, singleQuote: false },
});
writeFileSync(outFile, ts);
console.log(`wrote ${outFile} (${Object.keys(defs).length} definitions)`);
