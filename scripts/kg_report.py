"""Write out/kg_report.md: signal, tuple, blocked, archetype, tier and flag counts plus the test customers (Agent KG).

Run: .venv/bin/python scripts/kg_report.py [--graph]   (--graph also exports out/kg/kg_nodes.jsonl, kg_edges.jsonl)
"""

from __future__ import annotations

import argparse
import collections
import statistics
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from nba.data import load_workbook  # noqa: E402
from nba.kg.graph import export_graph  # noqa: E402
from nba.kg.policy import load_policy  # noqa: E402
from nba.kg.rules import generate_candidates  # noqa: E402
from nba.kg.segments import triage  # noqa: E402
from nba.kg.signals import extract_signals  # noqa: E402
from nba.state import build_states, population  # noqa: E402

TEST_CUSTOMERS = ["MG-100051", "MG-100060", "MG-100096", "MG-100186", "MG-100068", "MG-100023", "MG-100112",
                  "MG-100009", "MG-100659", "MG-100035", "MG-100087", "MG-100004", "MG-100012", "MG-100325", "MG-100001"]


def table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--graph", action="store_true", help="also export out/kg/kg_nodes.jsonl and kg_edges.jsonl")
    args = ap.parse_args()
    t0 = time.time()
    tables = load_workbook()
    policy = load_policy(tables=tables)
    states = build_states(tables, policy.config["eval_time"], snapshot_mode=policy.config["snapshot_mode"])
    pop = population(tables)
    res = {}
    for cid, s in states.items():
        sig = extract_signals(s, policy)
        cands, blocked = generate_candidates(s, sig, policy, "sie")
        res[cid] = (sig, cands, blocked, triage(s, sig, policy, pop))
    elapsed = time.time() - t0

    sig_n = collections.Counter(x.id for sig, *_ in res.values() for x in sig)
    origin = collections.Counter(c.origin for _, cands, *_ in res.values() for c in cands)
    blocked_n = collections.Counter(b.rule_id for *_, blocked, _ in res.values() for b in blocked)
    no_tuple = sum(1 for _, cands, *_ in res.values() if not cands)
    arch = collections.defaultdict(list)
    for cid, (*_, t) in res.items():
        arch[t.archetype.id].append(states[cid].one("customer_value"))
    tiers = collections.Counter(t.urgency_tier for *_, t in res.values())
    flags = collections.Counter(f.id for *_, t in res.values() for f in t.flags)
    outliers = sum(t.outlier for *_, t in res.values())

    lines = [
        "# KG report",
        "",
        f"Generated by `scripts/kg_report.py` for {len(states)} customers at eval {next(iter(states.values())).eval_time} "
        f"in {elapsed:.2f} s. Policy {policy.version}.",
        "",
        "## Signals",
        "",
        table(["Signal", "Label", "Customers"], [[s.id, s.label, sig_n.get(s.id, 0)] for s in policy.enabled_signals]),
        "",
        "## Tuples and blocks",
        "",
        table(["Origin", "Tuples"], [[k, v] for k, v in sorted(origin.items())]),
        "",
        f"Customers without any tuple: {no_tuple}.",
        "",
        table(["Blocked rule", "Rows"], [[k, v] for k, v in sorted(blocked_n.items())]),
        "",
        "## Triage",
        "",
        table(["Archetype", "Name", "Customers", "CLV median", "Churn median"],
              [[a, policy.archetypes[a], len(v), round(statistics.median(float(x["clv_eur"]) for x in v)),
                round(statistics.median(float(x["churn_prob_12m"]) for x in v), 3)] for a, v in sorted(arch.items())]),
        "",
        table(["Tier", "Customers"], [[k, v] for k, v in sorted(tiers.items())]),
        "",
        table(["Flag", "Customers"], [[k, v] for k, v in sorted(flags.items())]) + f"\n\nOutliers: {outliers}.",
        "",
        "## Test and representative customers",
        "",
    ]
    rows = []
    for cid in TEST_CUSTOMERS:
        sig, cands, blocked, t = res[cid]
        by_origin = collections.Counter(c.origin for c in cands)
        key_blocks = sorted({f"{b.offer_id}:{b.rule_id}" for b in blocked if b.rule_id != "DATA-MISSING"})
        rows.append([cid, t.archetype.id, t.urgency_tier, ", ".join(s.id for s in sig) or "—",
                     ", ".join(f"{k} {v}" for k, v in sorted(by_origin.items())) or "—",
                     ", ".join(sorted({c.offer_id for c in cands if c.origin != 'generic'})) or "—",
                     "; ".join(key_blocks) or "—"])
    lines.append(table(["Customer", "Archetype", "Tier", "Signals", "Tuples by origin", "Signal/service offers", "Blocked"], rows))
    out = REPO / "out" / "kg_report.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(REPO)} ({elapsed:.2f} s)")
    if args.graph:
        archetypes = {cid: t.archetype.id for cid, (*_, t) in res.items()}
        n, e = export_graph(states, policy, REPO / "out" / "kg", archetypes)
        print(f"wrote out/kg/kg_nodes.jsonl ({n} nodes) and kg_edges.jsonl ({e} edges)")


if __name__ == "__main__":
    main()
